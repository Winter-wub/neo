// ชื่อที่ซ้ำกับคำทั่วไป (ดีมาก"เลย", "ตาก"ผ้า, "แพร่"เชื้อ) ต้องมีคำนำหน้าว่าเป็นสถานที่
const AMBIGUOUS = new Set(['เลย', 'ตาก', 'แพร่', 'ตรัง', 'น่าน']);
const CUE = /(?:ที่|แถว|จังหวัด|จ\.|เมือง|ประเทศ|อำเภอ|อ\.|เกาะ|ไป|ใน)\s?/g;
// คำที่ไม่ใช่ชื่อที่ (ตัดท้ายชื่อที่ตามหลังคำนำหน้า)
const STOP = /อากาศ|อากา|สภาพ|ฝน|ร้อน|หนาว|อุณหภูมิ|องศา|วันนี้|พรุ่งนี้|มะรืน|ตอนนี้|คืนนี้|เช้านี้|เย็นนี้|สัปดาห์|อาทิตย์|เป็น|ยังไง|อย่างไร|ไหม|มั้ย|บ้าง|จะ|ตก|มี|กี่|หรือ|ครับ|ค่ะ|คะ|นะ|ดี|ช่วง|ตอน|นีโอ|นี่โอ|ไง|ยัง|ได้|แล้ว|เลย|มาก|หน่อย|weather|\?|\s{2,}/i;
const NOT_PLACE = /^(?:บ้าน|นี้|นั้น|ตรงนี้|แถวนี้|ข้างนอก|ทาง|วัน|ตอน|เวลา|ช่วง)$/;

/** วัน: 0 วันนี้, 1 พรุ่งนี้, 2 มะรืน */
function dayOf(t) { return /มะรืน/.test(t) ? 2 : /พรุ่งนี้/.test(t) ? 1 : 0; }

/**
 * หาที่จากคำถาม: { kind:'fixed', lat, lon, name } | { kind:'province'|'query', query } | null (= เมืองบ้าน)
 */
function placeOf(text) {
  const t = String(text || '');
  for (const [k, v] of Object.entries(SPOTS)) if (t.includes(k)) return { kind: 'fixed', lat: v[0], lon: v[1], name: v[2] };
  const names = [...Object.keys(ALIASES), ...PROVINCES].sort((a, b) => b.length - a.length); // ชื่อยาวก่อน (นครศรีธรรมราช ก่อน นครศรี)
  for (const n of names) {
    const i = t.indexOf(n); if (i < 0) continue;
    if (AMBIGUOUS.has(n) && !/(?:ที่|จังหวัด|จ\.|เมือง|ไป)\s?$/.test(t.slice(0, i))) continue;
    return { kind: 'province', query: ALIASES[n] || n };
  }
  // ไม่อยู่ในรายชื่อ: เอาคำหลังคำนำหน้า เช่น "อากาศที่โตเกียวเป็นไง" → โตเกียว
  let m; CUE.lastIndex = 0;
  while ((m = CUE.exec(t))) {
    let rest = t.slice(m.index + m[0].length);
    const s = rest.search(STOP); if (s >= 0) rest = rest.slice(0, s);
    rest = rest.replace(/[^฀-๿A-Za-z\s.-]/g, '').trim();
    if (rest.length >= 2 && !NOT_PLACE.test(rest)) return { kind: 'query', query: rest };
  }
  // ชื่อที่ไม่มีคำนำหน้า เช่น "โตเกียวอากาศเป็นไง": ตัดประโยคที่คำที่ไม่ใช่ชื่อที่ แล้วเดาส่วนที่เหลือ (หาไม่เจอ = เมืองบ้าน เงียบ ๆ)
  for (let part of t.split(new RegExp(STOP.source, 'gi'))) {
    part = part.replace(/[^\u0E00-\u0E7FA-Za-z\s.-]/g, '').trim();
    if (part.length >= 3 && !NOT_PLACE.test(part) && !AMBIGUOUS.has(part)) return { kind: 'guess', query: part }; // server รับเฉพาะเมื่อชื่อที่หาเจอตรงคำนี้ทุกตัว
  }
  return null;
}

